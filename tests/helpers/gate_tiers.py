"""The two test-gate tiers (spec docs/superpowers/specs/
2026-11-06-two-tier-test-gate-design.md).

Everything is in the MERGE tier unless tests/gate_tiers/deep_pytest.txt or
deep_gtest.txt lists it: those run only in the FULL gate. Both lists are
GENERATED from the full gate's measured durations by
`uv run python tools/gate_tiers.py generate <full-gate artefact dir>`;
never hand-edit them.

Pure functions over paths and lists: the conftest marks deep pytest items
with them, tools/check_test_baseline.py filters gtest cases with them, and
tests/unit/test_gate_tiers.py checks the lists have not rotted.
"""
from __future__ import annotations

import ast
import json
import os
import re
from collections import defaultdict
from functools import lru_cache

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TIER_DIR = os.path.join(ROOT, "tests", "gate_tiers")
DEEP_PYTEST = os.path.join(TIER_DIR, "deep_pytest.txt")
DEEP_GTEST = os.path.join(TIER_DIR, "deep_gtest.txt")

# Generation targets (measured seconds of test time, this machine, Debug).
PYTEST_TARGET_S = 150.0
GTEST_TARGET_S = 25.0
# The full gate fails when the merge tier, projected from its own measured
# durations, costs more than this: the selection has rotted, regenerate.
PYTEST_FAIL_S = 200.0
GTEST_FAIL_S = 40.0

# Never demoted: the cheap tree-scanning guards (and this tier's own check).
PROTECTED_FILES = (
    "tests/unit/test_path_indirection.py",
    "tests/unit/test_install_write_guard.py",
    "tests/integration/test_no_install_writes.py",
    "tests/tools/test_raw_key_reads.py",
    "tests/unit/test_gate_tiers.py",
)
PROTECTED_DIRS = ("tests/docs/",)


def is_protected(path: str) -> bool:
    path = path.replace(os.sep, "/")
    return (path in PROTECTED_FILES or path.startswith(PROTECTED_DIRS)
            or "drift" in os.path.basename(path))


_HEADER = """\
# GENERATED by tools/gate_tiers.py from the full gate's measured durations.
# Do not hand-edit: regenerate with
#   uv run python tools/gate_tiers.py generate <full-gate artefact dir>
# {what}
# Everything NOT listed here runs in the merge gate (scripts/gate_merge.sh);
# everything runs in the full gate (scripts/gate_full.sh).
# Spec: docs/superpowers/specs/2026-11-06-two-tier-test-gate-design.md
"""


def _read_lines(path):
    if not os.path.isfile(path):
        return []
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                out.append(line)
    return out


# ── pytest ────────────────────────────────────────────────────────────────


def load_deep_pytest(path=DEEP_PYTEST) -> list:
    """Entries: a test file path, or 'path::function' (every parametrize case
    of it; a method is 'path::Class::method')."""
    return _read_lines(path)


def function_key(nodeid: str) -> str:
    """'path::func[param]' -> 'path::func' (the deep list's granularity)."""
    return nodeid.split("[", 1)[0]


def deep_matcher(entries):
    files = {e for e in entries if "::" not in e}
    funcs = {e for e in entries if "::" in e}

    def is_deep(nodeid: str) -> bool:
        return (nodeid.split("::", 1)[0] in files
                or function_key(nodeid) in funcs)
    return is_deep


# ── gtest ─────────────────────────────────────────────────────────────────


def load_deep_gtest(path=DEEP_GTEST) -> dict:
    """{binary name: set of gtest full names ('Suite.Case', 'P/Suite.Case/3')}."""
    out = defaultdict(set)
    for line in _read_lines(path):
        binary, _, name = line.partition(" ")
        if name:
            out[binary].add(name.strip())
    return dict(out)


def parse_gtest_list(text: str) -> list:
    """Full names from `<binary> --gtest_list_tests`."""
    names, suite = [], None
    for line in text.splitlines():
        if not line.strip():
            continue
        if not line.startswith(" "):
            suite = line.split("#", 1)[0].strip()
        elif suite:
            names.append(suite + line.split("#", 1)[0].strip())
    return names


def suite_of(name: str) -> str:
    """'P/Suite.Case/3' -> 'P/Suite' (gtest's own suite name)."""
    return name.rsplit(".", 1)[0] if "." in name else name


def uncovered_suites(all_names, deep) -> list:
    """Suites every one of whose cases is deep: an area the merge gate lost."""
    keep = defaultdict(bool)
    for n in all_names:
        keep[suite_of(n)] |= n not in deep
    return sorted(s for s, k in keep.items() if not k)


def gtest_filter(deep) -> str:
    """A negative --gtest_filter excluding `deep` (empty: run everything)."""
    return "" if not deep else "--gtest_filter=-" + ":".join(sorted(deep))


_GTEST_OK = re.compile(r"^\[       OK \] (\S+) \((\d+) ms\)$", re.M)


def gtest_case_ms(log_text: str) -> dict:
    return {m.group(1): int(m.group(2)) for m in _GTEST_OK.finditer(log_text)}


# ── area coverage ─────────────────────────────────────────────────────────


@lru_cache(maxsize=None)
def engine_areas() -> frozenset:
    """First-level engine packages and top-level engine modules."""
    eng = os.path.join(ROOT, "engine")
    out = set()
    for name in os.listdir(eng):
        p = os.path.join(eng, name)
        if os.path.isdir(p) and os.path.isfile(os.path.join(p, "__init__.py")):
            out.add(name)
        elif name.endswith(".py") and name != "__init__.py":
            out.add(name[:-3])
    return frozenset(out)


@lru_cache(maxsize=None)
def engine_imports(path: str, areas: frozenset) -> frozenset:
    """The engine areas a test file imports directly."""
    try:
        with open(path, encoding="utf-8") as fh:
            tree = ast.parse(fh.read())
    except (OSError, SyntaxError, ValueError):
        return frozenset()
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                parts = a.name.split(".")
                if parts[0] == "engine" and len(parts) > 1:
                    found.add(parts[1])
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            parts = node.module.split(".")
            if parts[0] != "engine":
                continue
            if len(parts) > 1:
                found.add(parts[1])
            else:
                found.update(a.name for a in node.names)
    return frozenset(found & areas)


@lru_cache(maxsize=None)
def all_test_files() -> tuple:
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "tests")):
        dirnames[:] = [d for d in dirnames if not d.startswith((".", "__"))]
        for f in filenames:
            if f.startswith("test_") and f.endswith(".py"):
                out.append(os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/"))
    return tuple(sorted(out))


@lru_cache(maxsize=None)
def tests_in_file(path: str) -> tuple:
    """'path::func' / 'path::Class::method' keys of a file's tests."""
    try:
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            tree = ast.parse(fh.read())
    except (OSError, SyntaxError, ValueError):
        return ()
    keys = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test"):
            keys.append("%s::%s" % (path, node.name))
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)) and sub.name.startswith("test"):
                    keys.append("%s::%s::%s" % (path, node.name, sub.name))
    return tuple(keys)


def file_is_merge(path: str, is_deep) -> bool:
    """Whether at least one of the file's tests stays in the merge tier."""
    keys = tests_in_file(path)
    return any(not is_deep(k) for k in keys) if keys else not is_deep(path + "::x")


def coverage_gaps(entries) -> list:
    """Areas the deep list leaves without merge-tier coverage:
    'tests/<dir>' with no merge-tier file, and engine areas imported by some
    test file but by no merge-tier one."""
    is_deep = deep_matcher(entries)
    areas = engine_areas()
    files = all_test_files()
    merge = {f for f in files if file_is_merge(f, is_deep)}
    gaps = []
    dirs = defaultdict(list)
    for f in files:
        dirs["/".join(f.split("/")[:2])].append(f)
    for d, fs in sorted(dirs.items()):
        if d.endswith(".py"):
            continue
        if not any(f in merge for f in fs):
            gaps.append(d)
    imported_by_any, imported_by_merge = set(), set()
    for f in files:
        imp = engine_imports(os.path.join(ROOT, f), areas)
        imported_by_any |= imp
        if f in merge:
            imported_by_merge |= imp
    gaps += ["engine/%s" % a for a in sorted(imported_by_any - imported_by_merge)]
    return gaps


@lru_cache(maxsize=None)
def cpp_tests() -> frozenset:
    """{(suite, case)} named by a TEST*-macro under native/tests."""
    import glob
    pat = re.compile(r"\b(?:TYPED_)?TEST(?:_F|_P)?\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)")
    found = set()
    for f in glob.glob(os.path.join(ROOT, "native", "tests", "**", "*.cc"), recursive=True):
        with open(f, encoding="utf-8", errors="replace") as fh:
            found |= set(pat.findall(fh.read()))
    return frozenset(found)


def split_gtest(name: str):
    """'Inst/Suite.Case/3' -> ('Suite', 'Case')."""
    suite, _, case = name.rpartition(".")
    return suite.rsplit("/", 1)[-1], case.split("/", 1)[0]


def pytest_entry_exists(entry: str) -> bool:
    path = entry.split("::", 1)[0]
    if not os.path.isfile(os.path.join(ROOT, path)):
        return False
    return "::" not in entry or function_key(entry) in tests_in_file(path)


# ── generation ────────────────────────────────────────────────────────────


def generate_pytest(durations: dict, target_s=PYTEST_TARGET_S):
    """Choose the deep functions: the slowest (by summed measured seconds per
    function) go until the rest fits `target_s`; a protected file is never
    chosen; a pick that would leave an area without merge coverage is
    skipped. A file every function of which is deep is listed as the file."""
    per_func = defaultdict(float)
    for nodeid, secs in durations.items():
        if pytest_entry_exists(function_key(nodeid)):   # measured, since removed
            per_func[function_key(nodeid)] += secs
    remaining = sum(per_func.values())
    chosen = []
    for key, secs in sorted(per_func.items(), key=lambda kv: (-kv[1], kv[0])):
        if remaining <= target_s:
            break
        if is_protected(key.split("::", 1)[0]):
            continue
        if coverage_gaps(chosen + [key]) != coverage_gaps(chosen):
            continue
        chosen.append(key)
        remaining -= secs
    by_file = defaultdict(set)
    for k in chosen:
        by_file[k.split("::", 1)[0]].add(k)
    entries = []
    for f, ks in sorted(by_file.items()):
        all_keys = set(tests_in_file(f))
        entries += [f] if all_keys and all_keys <= ks else sorted(ks)
    return entries, remaining


def generate_gtest(case_ms: dict, target_s=GTEST_TARGET_S):
    """case_ms: {binary: {name: ms}}. The slowest cases go deep until the
    rest fits; each suite keeps its fastest case (its merge coverage)."""
    known = cpp_tests()
    case_ms = {b: {n: ms for n, ms in cs.items() if split_gtest(n) in known}
               for b, cs in case_ms.items()}
    keep_one = set()
    for binary, cases in case_ms.items():
        fastest = {}
        for n, ms in cases.items():
            s = suite_of(n)
            if s not in fastest or (ms, n) < fastest[s]:
                fastest[s] = (ms, n)
        keep_one |= {(binary, n) for _ms, n in fastest.values()}
    flat = sorted(((ms, b, n) for b, cs in case_ms.items() for n, ms in cs.items()),
                  key=lambda t: (-t[0], t[1], t[2]))
    remaining = sum(t[0] for t in flat) / 1000.0
    chosen = defaultdict(set)
    for ms, b, n in flat:
        if remaining <= target_s:
            break
        if (b, n) in keep_one:
            continue
        chosen[b].add(n)
        remaining -= ms / 1000.0
    return dict(chosen), remaining


def write_pytest(entries, remaining, path=DEEP_PYTEST):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(_HEADER.format(what="pytest: files, or path::function (all its parametrize cases). "
                                     "Merge tier measured at %.0f s of test time." % remaining))
        for e in entries:
            fh.write(e + "\n")


def write_gtest(chosen, remaining, path=DEEP_GTEST):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(_HEADER.format(what="gtest: '<binary> <full gtest name>'. "
                                     "Merge tier measured at %.0f s of test time." % remaining))
        for b in sorted(chosen):
            for n in sorted(chosen[b]):
                fh.write("%s %s\n" % (b, n))


def project_pytest(durations: dict, entries) -> float:
    is_deep = deep_matcher(entries)
    return sum(s for n, s in durations.items() if not is_deep(n))


def project_gtest(case_ms: dict, deep: dict) -> float:
    return sum(ms for b, cs in case_ms.items() for n, ms in cs.items()
               if n not in deep.get(b, ())) / 1000.0


def load_artefacts(artefact_dir):
    """(pytest durations {nodeid: s}, gtest {binary: {name: ms}}) from a full
    gate's artefact directory."""
    with open(os.path.join(artefact_dir, "pytest_durations.json"), encoding="utf-8") as fh:
        durations = json.load(fh)
    case_ms = {}
    for f in sorted(os.listdir(artefact_dir)):
        if f.startswith("inproc_") and f.endswith(".log"):
            with open(os.path.join(artefact_dir, f), encoding="utf-8", errors="replace") as fh:
                case_ms[f[len("inproc_"):-len(".log")]] = gtest_case_ms(fh.read())
    return durations, case_ms
