"""Where BC's stock scripts come from: the retail install's own ``.pyc``.

The runtime authority for stock modules (spec
docs/superpowers/specs/2026-11-11-no-sdk-runtime-design.md, §2 decisions
6-8, §4.1-4.2). The game never reads the SDK.

* A stock module exists iff the committed manifest
  (``engine/stock_manifest.json``, generated by
  ``tools/gen_stock_manifest.py``) lists it. Stray ``.py`` and unlisted
  ``.pyc`` in the install are invisible: mods go through the Mods system.
* Listed files are found under ``paths.stock_scripts()``, resolved at use
  and matched case-insensitively (``case_paths.resolve``), so a Linux install
  spelled ``Scripts/Ships`` still resolves.
* ``load_tree`` lifts a listed ``.pyc`` through ``engine.py15``. A file whose
  hash is in no known retail set still loads, after ONE warning per path per
  process (decision 6). A missing or unliftable listed file raises
  ``StockScriptError`` naming it (decision 7).
* ``SYNTHETIC_PACKAGES``: package names the SDK shipped as an empty
  ``__init__.py`` and retail lacks; the loaders create them empty.

Never write lifted text, or anything derived from a lifted module, to disk:
the tree goes straight to the caller.

The fixture-tree API (``add_fixture_tree``, ``clear_fixture_trees``,
``fixture_tgl_roots``) is TEST-ONLY (decision 8): it lets the test loader
serve the SDK's ``Custom/Tutorial`` sample as source. Fixtures resolve after
the manifest and never shadow a listed module. The game never calls it.
"""
from __future__ import annotations

import ast
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from engine import paths, py15
from engine.core import case_paths
from engine.py15 import marshal15
from engine.py15.source import fix_source, read_source

__all__ = [
    "SYNTHETIC_PACKAGES", "StockFile", "StockScriptError", "add_fixture_tree",
    "children", "clear_fixture_trees", "configure", "find", "find_by_leaf",
    "fixture_tgl_roots", "is_stock", "load_tree", "top_level_functions",
]

SYNTHETIC_PACKAGES: tuple[str, ...] = ("Custom",)

_INIT = "__init__"
# Python 1.5 opcodes ending a class body: LOAD_LOCALS, RETURN_VALUE.
_CLASS_BODY_END = bytes([82, 83])


@dataclass(frozen=True)
class StockFile:
    rel: str            # logical, no extension, manifest spelling ("Bridge")
    path: Path          # on disk
    is_package: bool
    is_fixture: bool


class StockScriptError(ImportError):
    """A listed stock module that cannot be loaded (missing or unliftable)."""

    def __init__(self, message: str, path) -> None:
        super().__init__(message, path=str(path))


@dataclass(frozen=True)
class _Entry:
    rel: str
    key: str            # the manifest key, with ".pyc"
    is_package: bool
    hashes: frozenset


class _Index:
    """One manifest indexed by folded logical name, for one root."""

    def __init__(self, root: Path, modules: dict) -> None:
        self.root = root
        self.entries: dict[str, _Entry] = {}
        self.stock_names: set[str] = set()
        for key, hashes in modules.items():
            stem = key[:-len(".pyc")] if key.lower().endswith(".pyc") else key
            self.stock_names.add(stem.casefold())
            is_package = stem.rsplit("/", 1)[-1] == _INIT
            rel = stem.rsplit("/", 1)[0] if is_package and "/" in stem else stem
            entry = _Entry(rel, key, is_package, frozenset(hashes))
            folded = rel.casefold()
            # A package beats a same-named module, as in Python's import.
            if folded not in self.entries or is_package:
                self.entries[folded] = entry
        self._paths: dict[str, Path] = {}
        self.by_path: dict[str, _Entry] = {}

    def file(self, entry: _Entry) -> StockFile:
        path = self._paths.get(entry.key)
        if path is None:
            found = case_paths.resolve(self.root, entry.key)
            path = found if found is not None else self.root / entry.key
            self._paths[entry.key] = path
            self.by_path[str(path)] = entry
        return StockFile(entry.rel, path, entry.is_package, False)


# --- configuration --------------------------------------------------------

_manifest_override: Optional[dict] = None
_root_override: Optional[Path] = None
_committed: Optional[dict] = None
_index: Optional[_Index] = None
_index_manifest: Optional[dict] = None
_warned: set = set()


def configure(manifest_modules: Optional[dict] = None,
              scripts_root: Optional[Path] = None) -> None:
    """Inject a manifest ``modules`` mapping and a scripts root (tests).
    ``None`` = the committed manifest / ``paths.stock_scripts()`` at use."""
    global _manifest_override, _root_override, _index, _index_manifest
    _manifest_override = manifest_modules
    _root_override = Path(scripts_root) if scripts_root is not None else None
    _index = None
    _index_manifest = None


def _manifest() -> dict:
    global _committed
    if _manifest_override is not None:
        return _manifest_override
    if _committed is None:
        text = Path(__file__).with_name("stock_manifest.json").read_text("utf-8")
        _committed = json.loads(text)["modules"]
    return _committed


def _current() -> _Index:
    """The index for the current (root, manifest); rebuilt only on change."""
    global _index, _index_manifest
    root = _root_override if _root_override is not None else paths.stock_scripts()
    manifest = _manifest()
    if _index is None or _index.root != root or _index_manifest is not manifest:
        _index = _Index(root, manifest)
        _index_manifest = manifest
    return _index


def _fold(logical: str) -> str:
    return logical.replace("\\", "/").strip("/").casefold()


# --- fixtures (test-only, decision 8) --------------------------------------

_fixture_files: dict[str, StockFile] = {}
_fixture_tgl: list[Path] = []


def add_fixture_tree(root: Path, prefix: str,
                     tgl_root: Optional[Path] = None) -> None:
    """TEST-ONLY: serve every ``.py`` under ``root/prefix`` as a fixture
    module named by its path relative to ``root``."""
    root = Path(root)
    base = case_paths.resolve(root, prefix)
    if base is not None and base.is_dir():
        for py in sorted(base.rglob("*.py")):
            parts = py.relative_to(root).with_suffix("").parts
            is_package = parts[-1] == _INIT
            rel = "/".join(parts[:-1] if is_package else parts)
            _fixture_files.setdefault(
                rel.casefold(), StockFile(rel, py, is_package, True))
    if tgl_root is not None:
        _fixture_tgl.append(Path(tgl_root))


def clear_fixture_trees() -> None:
    """TEST-ONLY: forget every fixture tree and TGL root."""
    _fixture_files.clear()
    _fixture_tgl.clear()


def fixture_tgl_roots() -> tuple[Path, ...]:
    """TEST-ONLY: the TGL roots given to ``add_fixture_tree``, in order."""
    return tuple(_fixture_tgl)


# --- lookups ---------------------------------------------------------------

def find(logical: str) -> Optional[StockFile]:
    """The listed module (or package) named ``logical``, any case, no
    extension; else a fixture; else None."""
    folded = _fold(logical)
    index = _current()
    entry = index.entries.get(folded)
    if entry is not None:
        return index.file(entry)
    return _fixture_files.get(folded)


def _select(keep) -> list[StockFile]:
    """Listed then fixture files whose (rel, is_package) pass ``keep``,
    sorted by ``rel``. Only the kept entries are resolved on disk."""
    index = _current()
    found = [index.file(e) for e in index.entries.values()
             if keep(e.rel, e.is_package)]
    found += [sf for folded, sf in _fixture_files.items()
              if folded not in index.entries and keep(sf.rel, sf.is_package)]
    return sorted(found, key=lambda sf: sf.rel)


def find_by_leaf(name: str) -> list[StockFile]:
    """Every listed (or fixture) non-package module whose last segment folds
    equal to ``name``, sorted by ``rel``."""
    folded = name.casefold()
    return _select(lambda rel, is_package: not is_package
                   and rel.rsplit("/", 1)[-1].casefold() == folded)


def children(rel_dir: str) -> list[StockFile]:
    """The direct module (and package) children of folder ``rel_dir``."""
    folded = _fold(rel_dir)
    return _select(lambda rel, _pkg: (
        rel.rsplit("/", 1)[0].casefold() if "/" in rel else "") == folded)


def is_stock(rel: str) -> bool:
    """Whether ``rel`` (``.py``/``.pyc``/no extension, any case) names a
    listed stock module or package. Fixtures are not stock."""
    folded = _fold(rel)
    for ext in (".pyc", ".py"):
        if folded.endswith(ext):
            folded = folded[:-len(ext)]
            break
    index = _current()
    return folded in index.stock_names or (
        folded in index.entries and index.entries[folded].is_package)


def top_level_functions(sf: StockFile) -> dict[str, tuple[str, ...]]:
    """Module-level function name -> argument names, read from the code
    object (a ``.pyc``) or the source (a fixture). Never lifts."""
    if sf.is_fixture:
        tree = ast.parse(fix_source(read_source(sf.path)), str(sf.path))
        return {node.name: tuple(a.arg for a in node.args.args)
                for node in tree.body if isinstance(node, ast.FunctionDef)}
    code = marshal15.load_pyc(sf.path.read_bytes())
    return {c.name: tuple(c.varnames[:c.argcount]) for c in code.consts
            if isinstance(c, marshal15.Code15) and not c.name.startswith("<")
            and not c.code.endswith(_CLASS_BODY_END)}


# --- loading ---------------------------------------------------------------

def _entry_for(path: Path) -> Optional[_Entry]:
    index = _current()
    entry = index.by_path.get(str(path))
    if entry is not None:
        return entry
    try:
        rel = path.relative_to(index.root).as_posix()
    except ValueError:
        return None
    stem = rel[:-len(".pyc")] if rel.lower().endswith(".pyc") else rel
    parts = stem.split("/")
    logical = "/".join(parts[:-1]) if parts[-1].casefold() == _INIT else stem
    return index.entries.get(logical.casefold())


def load_tree(path: str, fullname: str) -> ast.Module:
    """The module AST of a stock file: a listed ``.pyc`` lifted, or a
    fixture ``.py`` through the 1.5 source fixer."""
    p = Path(path)
    if p.suffix.lower() == ".py":
        return ast.parse(fix_source(read_source(p)), str(p))
    entry = _entry_for(p)
    if entry is None:
        raise StockScriptError(
            "stock module %s (%s) is not in the stock manifest"
            % (fullname, p), p)
    try:
        data = p.read_bytes()
    except OSError as exc:
        raise StockScriptError(
            "stock module %s: cannot read scripts/%s (%s): %s"
            % (fullname, entry.key, p, exc), p) from exc
    digest = hashlib.blake2b(data, digest_size=16).hexdigest()
    if digest not in entry.hashes and str(p) not in _warned:
        _warned.add(str(p))
        print("[stock-scripts] scripts/%s differs from every known retail "
              "copy (the install may be modded); loading it anyway"
              % entry.key, flush=True)
    try:
        return py15.lift(data)
    except py15.Py15Unsupported as exc:
        raise StockScriptError(
            "stock module %s: scripts/%s (%s) cannot be lifted: %s"
            % (fullname, entry.key, p, exc), p) from exc
