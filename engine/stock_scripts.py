SYNTHETIC_PACKAGES: tuple[str, ...] = ("Custom",)

_INIT = "__init__"
# Python 1.5 opcodes ending a class body: LOAD_LOCALS, RETURN_VALUE.
_CLASS_BODY_END = bytes([82, 83])


@dataclass(frozen=True)
class StockFile:
    rel: str            # logical, no extension, manifest spelling ("Bridge")
    path: Path          # on disk
    is_package: bool
    is_fixture: bool


class StockScriptError(ImportError):
    """A listed stock module that cannot be loaded (missing or unliftable)."""

    def __init__(self, message: str, path) -> None:
        super().__init__(message, path=str(path))


@dataclass(frozen=True)
class _Entry:
    rel: str
    key: str            # the manifest key, with ".pyc"
    is_package: bool
    hashes: frozenset


class _Index:
    """One manifest indexed by folded logical name, for one root."""

    def __init__(self, root: Path, modules: dict) -> None:
        self.root = root
        self.entries: dict[str, _Entry] = {}
        for key, hashes in modules.items():
            stem = key[:-len(".pyc")] if key.lower().endswith(".pyc") else key
            is_package = stem.rsplit("/", 1)[-1] == _INIT
            rel = stem.rsplit("/", 1)[0] if is_package and "/" in stem else stem
            entry = _Entry(rel, key, is_package, frozenset(hashes))
            folded = rel.casefold()
            # A package beats a same-named module, as in Python's import.
            if folded not in self.entries or is_package:
                self.entries[folded] = entry
        # Non-package entries by folded last segment, for find_by_leaf.
        self.by_leaf: dict[str, list[_Entry]] = {}
        for entry in self.entries.values():
            if not entry.is_package:
                leaf = entry.rel.rsplit("/", 1)[-1].casefold()
                self.by_leaf.setdefault(leaf, []).append(entry)
        self._paths: dict[str, Path] = {}
        self.by_path: dict[str, _Entry] = {}

    def file(self, entry: _Entry) -> StockFile:
        path = self._paths.get(entry.key)
        if path is None:
            found = case_paths.resolve(self.root, entry.key)
            path = found if found is not None else self.root / entry.key
            self._paths[entry.key] = path
            self.by_path[str(path)] = entry
        return StockFile(entry.rel, path, entry.is_package, False)


# --- configuration --------------------------------------------------------

_manifest_override: Optional[dict] = None
_root_override: Optional[Path] = None
_committed: Optional[dict] = None
_index: Optional[_Index] = None
_index_manifest: Optional[dict] = None
_warned: set = set()
_required: dict = {}      # require_install's memo, _memo_key(root) -> check
# (paths.game_root(), paths.stock_scripts()) for the last game root seen, so
# the case-blind "scripts" lookup runs once per root, not once per call.
_scripts_memo: Optional[tuple[Path, Path]] = None


def configure(manifest_modules: Optional[dict] = None,
              scripts_root: Optional[Path] = None) -> None:
    """Inject a manifest ``modules`` mapping and a scripts root (tests).
    ``None`` = the committed manifest / ``paths.stock_scripts()`` at use."""
    global _manifest_override, _root_override, _index, _index_manifest
    global _scripts_memo
    _manifest_override = manifest_modules
    _root_override = Path(scripts_root) if scripts_root is not None else None
    _index = None
    _index_manifest = None
    _scripts_memo = None
    _required.clear()


def _manifest() -> dict:
    global _committed
    if _manifest_override is not None:
        return _manifest_override
    if _committed is None:
        # Package data, read through importlib.resources: this module also
        # writes (the verdict cache), and must not build a path from its own
        # location (tests/unit/test_install_write_guard.py).
        text = (importlib.resources.files("engine")
                .joinpath("stock_manifest.json").read_text("utf-8"))
        _committed = json.loads(text)["modules"]
    return _committed


def _scripts_root() -> Path:
    """``paths.stock_scripts()``, re-resolved only when the game root
    changes (the root is still read at every use)."""
    global _scripts_memo
    game = paths.game_root()
    if _scripts_memo is None or _scripts_memo[0] != game:
        _scripts_memo = (game, paths.stock_scripts())
    return _scripts_memo[1]


def _current() -> _Index:
    """The index for the current (root, manifest); rebuilt only on change."""
    global _index, _index_manifest
    root = _root_override if _root_override is not None else _scripts_root()
    manifest = _manifest()
    if _index is None or _index.root != root or _index_manifest is not manifest:
        _index = _Index(root, manifest)
        _index_manifest = manifest
    return _index


def root() -> Path:
    """The scripts root stock files are found under: the injected one, else
    ``paths.stock_scripts()`` (resolved at use)."""
    return _root_override if _root_override is not None else _scripts_root()


def _fold(logical: str) -> str:
    return logical.replace("\\", "/").strip("/").casefold()


# --- fixtures (test-only, decision 8) --------------------------------------

_fixture_files: dict[str, StockFile] = {}
_fixture_tgl: list[Path] = []


def add_fixture_tree(root: Path, prefix: str,
                     tgl_root: Optional[Path] = None) -> None:
    """TEST-ONLY: serve every ``.py`` under ``root/prefix`` as a fixture
    module named by its path relative to ``root``."""
    root = Path(root)
    base = case_paths.resolve(root, prefix)
    if base is not None and base.is_dir():
        for py in sorted(base.rglob("*.py")):
            parts = py.relative_to(root).with_suffix("").parts
            is_package = parts[-1] == _INIT
            rel = "/".join(parts[:-1] if is_package else parts)
            _fixture_files.setdefault(
                rel.casefold(), StockFile(rel, py, is_package, True))
    if tgl_root is not None:
        _fixture_tgl.append(Path(tgl_root))


def clear_fixture_trees() -> None:
    """TEST-ONLY: forget every fixture tree and TGL root."""
    _fixture_files.clear()
    _fixture_tgl.clear()


def fixture_tgl_roots() -> tuple[Path, ...]:
    """TEST-ONLY: the TGL roots given to ``add_fixture_tree``, in order."""
    return tuple(_fixture_tgl)


# --- lookups ---------------------------------------------------------------

def find(logical: str) -> Optional[StockFile]:
    """The listed module (or package) named ``logical``, any case, no
    extension; else a fixture; else None."""
    folded = _fold(logical)
    index = _current()
    entry = index.entries.get(folded)
    if entry is not None:
        return index.file(entry)
    return _fixture_files.get(folded)


def _select(keep) -> list[StockFile]:
    """Listed then fixture files whose (rel, is_package) pass ``keep``,
    sorted by ``rel``. Only the kept entries are resolved on disk."""
    index = _current()
    found = [index.file(e) for e in index.entries.values()
             if keep(e.rel, e.is_package)]
    found += [sf for folded, sf in _fixture_files.items()
              if folded not in index.entries and keep(sf.rel, sf.is_package)]
    return sorted(found, key=lambda sf: sf.rel)


def find_by_leaf(name: str) -> list[StockFile]:
    """Every listed (or fixture) non-package module whose last segment folds
    equal to ``name``, sorted by ``rel``."""
    folded = name.casefold()
    index = _current()
    found = [index.file(e) for e in index.by_leaf.get(folded, ())]
    found += [sf for key, sf in _fixture_files.items()
              if key not in index.entries and not sf.is_package
              and sf.rel.rsplit("/", 1)[-1].casefold() == folded]
    return sorted(found, key=lambda sf: sf.rel)


def modules() -> list[StockFile]:
    """Every listed module and package, then fixtures, sorted by ``rel``."""
    return _select(lambda _rel, _pkg: True)


def children(rel_dir: str) -> list[StockFile]:
    """The direct module (and package) children of folder ``rel_dir``."""
    folded = _fold(rel_dir)
    return _select(lambda rel, _pkg: (
        rel.rsplit("/", 1)[0].casefold() if "/" in rel else "") == folded)


def is_stock(rel: str) -> bool:
    """Whether ``rel`` (``.py``/``.pyc``/no extension, any case) names a
    listed stock module or package. Fixtures are not stock."""
    folded = _fold(rel)
    for ext in (".pyc", ".py"):
        if folded.endswith(ext):
            folded = folded[:-len(ext)]
            break
    return folded in _stock_names()


_names_memo: Optional[tuple[dict, frozenset]] = None


def _stock_names() -> frozenset:
    """Every folded listed stem, plus each listed package's folded name.
    Read from the manifest alone, never the game root: ``mods.classify``
    asks while booting with roots held in hand, not configured."""
    global _names_memo
    manifest = _manifest()
    if _names_memo is None or _names_memo[0] is not manifest:
        names = set()
        for key in manifest:
            stem = key[:-len(".pyc")] if key.lower().endswith(".pyc") else key
            names.add(stem.casefold())
            head, _, leaf = stem.rpartition("/")
            if leaf == _INIT and head:
                names.add(head.casefold())
        _names_memo = (manifest, frozenset(names))
    return _names_memo[1]


def is_mission_script(sf: StockFile) -> bool:
    """Whether ``sf`` is a mission script: a top-level ``Initialize`` whose
    first argument is ``pMission`` (an episode's takes ``pEpisode``)."""
    if sf.is_package:
        return False
    args = top_level_functions(sf).get("Initialize", ())
    return args[:1] == ("pMission",)


def top_level_functions(sf: StockFile) -> dict[str, tuple[str, ...]]:
    """Module-level function name -> argument names, read from the code
    object (a ``.pyc``) or the source (a fixture). Never lifts."""
    if sf.is_fixture:
        tree = ast.parse(fix_source(read_source(sf.path)), str(sf.path))
        return {node.name: tuple(a.arg for a in node.args.args)
                for node in tree.body if isinstance(node, ast.FunctionDef)}
    try:
        code = marshal15.load_pyc(sf.path.read_bytes())
    except OSError as exc:
        raise StockScriptError(
            "stock module %s: cannot read %s: %s" % (sf.rel, sf.path, exc),
            sf.path) from exc
    except marshal15.Py15FormatError as exc:
        raise StockScriptError(
            "stock module %s: %s is not readable Python 1.5 bytecode: %s"
            % (sf.rel, sf.path, exc), sf.path) from exc
    return {c.name: tuple(c.varnames[:c.argcount]) for c in code.consts
            if isinstance(c, marshal15.Code15) and not c.name.startswith("<")
            and not c.code.endswith(_CLASS_BODY_END)}


def _fixture_at(path: Path) -> Optional[StockFile]:
    for sf in _fixture_files.values():
        if sf.path == path:
            return sf
    return None


def owns(path) -> bool:
    """Whether ``load_tree`` is the loader for the file at ``path``: it is
    under the scripts root, or a registered fixture. (An unlisted file under
    the root is owned too, so ``load_tree`` refuses it loudly.)"""
    p = Path(path)
    if _fixture_at(p) is not None:
        return True
    try:
        p.relative_to(root())
    except ValueError:
        return False
    return True


def logical_rel(path) -> Optional[str]:
    """The listed (or fixture) file at ``path`` as a path under the scripts
    root in the manifest's spelling, with its suffix ("ships/Galaxy.pyc",
    "Bridge/__init__.pyc"); None for anything else."""
    p = Path(path)
    sf = _fixture_at(p)
    if sf is not None:
        return sf.rel + ("/" + _INIT if sf.is_package else "") + p.suffix
    entry = _entry_for(p)
    return entry.key if entry is not None else None


# --- loading ---------------------------------------------------------------

def _digest(data: bytes) -> str:
    return hashlib.blake2b(data, digest_size=16).hexdigest()


def _warn_unknown(path: Path, key: str) -> None:
    """Decision 6's one warning per file per process, shared by the boot
    check and the loader so a file warns once whichever sees it first."""
    if str(path) in _warned:
        return
    _warned.add(str(path))
    print("[stock-scripts] scripts/%s differs from every known retail "
          "copy (the install may be modded); loading it anyway" % key,
          flush=True)


def _entry_for(path: Path) -> Optional[_Entry]:
    index = _current()
    entry = index.by_path.get(str(path))
    if entry is not None:
        return entry
    try:
        rel = path.relative_to(index.root).as_posix()
    except ValueError:
        return None
    stem = rel[:-len(".pyc")] if rel.lower().endswith(".pyc") else rel
    parts = stem.split("/")
    logical = "/".join(parts[:-1]) if parts[-1].casefold() == _INIT else stem
    return index.entries.get(logical.casefold())


def load_tree(path: str, fullname: str) -> ast.Module:
    """The module AST of a stock file: a listed ``.pyc`` lifted, or a
    fixture ``.py`` through the 1.5 source fixer."""
    p = Path(path)
    if p.suffix.lower() == ".py":
        if not any(sf.path == p for sf in _fixture_files.values()):
            raise StockScriptError(
                "stock module %s (%s) is source, and only a test fixture "
                "loads from source" % (fullname, p), p)
        return ast.parse(fix_source(read_source(p)), str(p))
    entry = _entry_for(p)
    if entry is None:
        raise StockScriptError(
            "stock module %s (%s) is not in the stock manifest"
            % (fullname, p), p)
    try:
        data = p.read_bytes()
    except OSError as exc:
        raise StockScriptError(
            "stock module %s: cannot read scripts/%s (%s): %s"
            % (fullname, entry.key, p, exc), p) from exc
    if _digest(data) not in entry.hashes:
        _warn_unknown(p, entry.key)
    try:
        return py15.lift(data)
    except py15.Py15Unsupported as exc:
        raise StockScriptError(
            "stock module %s: scripts/%s (%s) cannot be lifted: %s"
            % (fullname, entry.key, p, exc), p) from exc


# --- boot install check (spec §4.1a, decision 7) ---------------------------

_VERDICTS = "stock_lift_verdicts.json"
_VERDICT_FORMAT = 1
_HEX_HASH = re.compile(r"[0-9a-f]{32}")
_MAX_NAMED = 3


@dataclass(frozen=True)
class InstallCheck:
    """The verdict on one install's listed stock files. Every name is a
    ``scripts/<manifest key>`` display string."""
    ok: bool
    missing: tuple[str, ...]
    unliftable: tuple[str, ...]
    changed: tuple[str, ...]
    message: str


class StockInstallError(RuntimeError):
    """``require_install`` on an install that fails the check; the message
    is ``InstallCheck.message``."""


def _verdicts_path() -> Path:
    return paths.cache_dir() / _VERDICTS


def _load_verdicts() -> set:
    """The cached hashes known to lift; anything malformed reads as none."""
    try:
        data = json.loads(_verdicts_path().read_text("utf-8"))
    except (OSError, ValueError):
        return set()
    if not isinstance(data, dict) or data.get("format") != _VERDICT_FORMAT:
        return set()
    lifts = data.get("lifts")
    if not isinstance(lifts, list):
        return set()
    return {h for h in lifts if isinstance(h, str) and _HEX_HASH.fullmatch(h)}


def _save_verdicts(lifts: set) -> None:
    """Write the verdict cache atomically (temp file + ``os.replace``).
    A failure is reported once, never raised: the cache is an optimisation."""
    target = _verdicts_path()
    tmp = target.with_name("%s.%d.tmp" % (target.name, os.getpid()))
    text = json.dumps({"format": _VERDICT_FORMAT, "lifts": sorted(lifts)},
                      indent=1) + "\n"
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_text(text, "utf-8")
        os.replace(tmp, target)
    except OSError as exc:
        try:
            tmp.unlink()
        except OSError:
            pass
        paths.report_write_failure(target, exc)


def _proves_lift(path: Path) -> Optional[str]:
    """None when the file lifts AND the tree compiles (ruling R3); else why."""
    try:
        tree = py15.lift_file(path)
    except py15.Py15Unsupported as exc:
        return str(exc)
    except OSError as exc:
        return "%s: %s" % (type(exc).__name__, exc)
    try:
        compile(tree, str(path), "exec")
    except (SyntaxError, ValueError, TypeError, RecursionError) as exc:
        return "lifted code does not compile: %s: %s" % (type(exc).__name__, exc)
    return None


def _name_list(names) -> str:
    shown = list(names[:_MAX_NAMED])
    rest = len(names) - len(shown)
    if rest:
        return "%s and %d more" % (", ".join(shown), rest)
    if len(shown) == 1:
        return shown[0]
    return "%s and %s" % (", ".join(shown[:-1]), shown[-1])


def _message(missing: tuple, unliftable: tuple, reasons: dict) -> str:
    parts = []
    if missing:
        parts.append(
            "Your Bridge Commander scripts folder is incomplete: %s %s missing. "
            "Reinstall Bridge Commander or pick another install."
            % (_name_list(missing), "is" if len(missing) == 1 else "are"))
    if unliftable:
        first = unliftable[0]
        reason = reasons[first] if len(unliftable) == 1 else (
            "%s: %s" % (first, reasons[first]))
        parts.append(
            "BC Dauntless can't read %s in this Bridge Commander install (%s). "
            "It may be modded: please use a clean install."
            % (_name_list(unliftable), reason))
    return " ".join(parts)


def check_install(game_root: Path) -> InstallCheck:
    """Hash every listed file under ``game_root``'s scripts folder (any
    case). Missing -> ``missing``; an unknown hash -> ``changed`` plus the
    one-time warning, then lifted once unless the verdict cache already
    says that hash lifts; a failed lift or compile -> ``unliftable``."""
    game_root = Path(game_root)
    found = case_paths.resolve(game_root, "scripts")
    scripts = found if found is not None else game_root / "scripts"
    verdicts = _load_verdicts()
    learned = False
    missing, unliftable, changed = [], [], []
    reasons: dict = {}
    for key, hashes in sorted(_manifest().items()):
        shown = "scripts/" + key
        path = case_paths.resolve(scripts, key)
        if path is None or not path.is_file():
            missing.append(shown)
            continue
        try:
            data = path.read_bytes()
        except OSError as exc:
            unliftable.append(shown)
            reasons[shown] = "%s: %s" % (type(exc).__name__, exc.strerror or exc)
            continue
        digest = _digest(data)
        if digest in hashes:
            continue
        changed.append(shown)
        _warn_unknown(path, key)
        if digest in verdicts:
            continue
        reason = _proves_lift(path)
        if reason is None:
            verdicts.add(digest)
            learned = True
        else:
            unliftable.append(shown)
            reasons[shown] = reason
    if learned:
        _save_verdicts(verdicts)
    missing_t, unliftable_t = tuple(missing), tuple(unliftable)
    return InstallCheck(ok=not missing_t and not unliftable_t,
                        missing=missing_t, unliftable=unliftable_t,
                        changed=tuple(changed),
                        message=_message(missing_t, unliftable_t, reasons))


def validate_install(path) -> paths.Validation:
    """``paths.validate_game_root``, then (only if the markers pass) the
    stock scripts check. A failed check names its files in ``missing`` and
    carries the message as ``hint``."""
    validation = paths.validate_game_root(path)
    if not validation.ok:
        return validation
    check = check_install(validation.root)
    if check.ok:
        # Ruling R6: require_install (setup_sdk) reuses this passing check,
        # so a GUI boot hashes the install once.
        _required[_memo_key(validation.root)] = check
        return validation
    return paths.Validation(ok=False, root=validation.root,
                            missing=check.missing + check.unliftable,
                            hint=check.message)


def checked(resolution: paths.Resolution) -> paths.Resolution:
    """``resolution`` with a valid game root re-validated by
    ``validate_install``; a failure unresolves the game (keeping its
    source) so the first-run screen shows the problem."""
    if resolution.game is None:
        return resolution
    validation = validate_install(resolution.game)
    if validation.ok:
        return resolution
    return dataclasses.replace(resolution, game=None, game_validation=validation)


def _memo_key(game_root) -> str:
    return str(paths.normalise(game_root))


def require_install(game_root: Path) -> InstallCheck:
    """``check_install`` once per root per process (headless boot and
    ``setup_sdk``); raises ``StockInstallError`` with the message when the
    install fails. A passing ``validate_install`` of the same root counts."""
    key = _memo_key(game_root)
    check = _required.get(key)
    if check is None:
        check = check_install(Path(game_root))
        _required[key] = check
    if not check.ok:
        raise StockInstallError(check.message)
    return check


def forget_failed_checks() -> None:
    """Drop memoised FAILED checks so the next ``require_install`` re-checks;
    passing ones stay. The test suite's per-test reset calls it."""
    for key in [k for k, check in _required.items() if not check.ok]:
        del _required[key]
